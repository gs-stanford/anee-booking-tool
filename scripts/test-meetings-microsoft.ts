import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
import { db } from "../src/lib/db";
import { saveCalendarBooking } from "../src/lib/calendar-booking";
import { sealOutlook, syncConnectedOutlookCalendars, outlookAuthorizeUrl } from "../src/lib/outlook";
import { linkedMicrosoftUser, validateOutlookState } from "../src/lib/outlook-identity";
import { personalCalendarEvents } from "../src/lib/personal-calendar";
async function main() {
  assert.equal(process.env.DATABASE_URL,"file:/private/tmp/lab-calendar-test.db");
  const originalFetch=globalThis.fetch;
  const suffix=Date.now();
  const a=await db.user.create({data:{name:"Meeting Owner",email:`meeting-a-${suffix}@example.test`,passwordHash:"test"}});
  const b=await db.user.create({data:{name:"Meeting Guest",email:`meeting-b-${suffix}@example.test`,passwordHash:"test"}});
  const now=new Date("2026-11-20T20:00Z");
  const input={kind:"meeting",title:`Meeting ${suffix}`,location:"MERL",notes:"Discuss results",startDate:"2027-02-01",endDate:"2027-02-01",startTime:"14:00",endTime:"15:00",inviteeIds:[b.id]};
  try {
    await saveCalendarBooking(db,a,input,undefined,now);
    let event=await db.labEvent.findFirstOrThrow({where:{ownerId:a.id}});
    assert.equal(event.eventType,"meeting");assert.equal(event.notes,"Discuss results");assert.equal(event.impact,"");
    await assert.rejects(saveCalendarBooking(db,b,input,{id:event.id,version:0},now));
    await assert.rejects(saveCalendarBooking(db,a,{...input,kind:"event"},undefined,now),"impact remains mandatory for cross-impact events");
    await assert.rejects(saveCalendarBooking(db,a,{...input,teamsEnabled:"on"},{id:event.id,version:0},now));
    process.env.OUTLOOK_CLIENT_ID="test";process.env.OUTLOOK_CLIENT_SECRET="test";process.env.OUTLOOK_TENANT_ID="test";process.env.APP_URL="https://lab.example.test";process.env.OUTLOOK_TOKEN_ENCRYPTION_KEY=randomBytes(32).toString("base64");
    process.env.OUTLOOK_TEAMS_ENABLED="false";
    assert.equal(new URL(outlookAuthorizeUrl("s","v")).searchParams.get("scope")?.includes("OnlineMeetings"),false);
    process.env.OUTLOOK_TEAMS_ENABLED="true";
    assert.equal(new URL(outlookAuthorizeUrl("s","v")).searchParams.get("scope")?.includes("OnlineMeetings.ReadWrite"),true);
    // Guest is connected first to exercise the organizer-first Teams sync pass.
    for(const user of [b,a]) await db.outlookConnection.create({data:{userId:user.id,microsoftId:`ms-${user.id}`,email:user.email,refreshToken:sealOutlook(user.id)}});
    assert.equal((await linkedMicrosoftUser(db,`ms-${a.id}`)).id,a.id);
    await assert.rejects(linkedMicrosoftUser(db,"not-linked"));
    const state={mode:"connect",state:"state-value",verifier:"verifier",userId:a.id,expires:Date.now()+60000};
    assert.equal(validateOutlookState(sealOutlook(JSON.stringify(state)),state.state,a.id).mode,"connect");
    assert.throws(()=>validateOutlookState(sealOutlook(JSON.stringify(state)),state.state,b.id));
    assert.throws(()=>validateOutlookState(sealOutlook(JSON.stringify(state)),"wrong",a.id));
    assert.throws(()=>validateOutlookState(sealOutlook(JSON.stringify({...state,expires:0})),state.state,a.id));
    assert.equal(validateOutlookState(sealOutlook(JSON.stringify({...state,mode:"signin"})),state.state).mode,"signin");
    assert.throws(()=>validateOutlookState("tampered",state.state,a.id));
    await db.user.update({where:{id:b.id},data:{role:"TEMP"}});
    await assert.rejects(linkedMicrosoftUser(db,`ms-${b.id}`));
    await db.user.update({where:{id:b.id},data:{role:"MEMBER"}});
    await saveCalendarBooking(db,a,{...input,teamsEnabled:"on"},{id:event.id,version:0},now);
    const calls:{url:string;method:string;body:Record<string,unknown>;token:string}[]=[];
    globalThis.fetch=async(input,init)=>{
      const url=String(input),method=init?.method??"GET";
      if(url.includes("/token")) return Response.json({access_token:new URLSearchParams(String(init?.body)).get("refresh_token")});
      const body=init?.body?JSON.parse(String(init.body)):{};
      const token=new Headers(init?.headers).get("Authorization")??"";
      calls.push({url,method,body,token});
      if(url.endsWith("/me/calendars"))return Response.json({id:`calendar-${token}`});
      if(url.endsWith("/createOrGet"))return Response.json({id:"teams-id",joinWebUrl:"https://teams.microsoft.com/l/meetup-join/test"});
      if(method==="DELETE")return new Response(null,{status:204});
      return Response.json({id:`event-${calls.length}`});
    };
    await syncConnectedOutlookCalendars();
    assert.equal(calls.filter(c=>c.url.endsWith("/createOrGet")).length,1);
    assert.equal(calls.find(c=>c.url.endsWith("/createOrGet"))?.token,`Bearer ${a.id}`);
    const copies=calls.filter(c=>c.method==="POST"&&c.url.endsWith("/events"));
    assert.equal(copies.length,2);
    for(const copy of copies) assert.match(JSON.stringify(copy.body),/teams.microsoft.com/);
    assert.equal((await personalCalendarEvents(db,b.id,now))[0].notes.includes("Discuss results"),true);
    let count=calls.length;await syncConnectedOutlookCalendars();assert.equal(calls.length,count,"idempotent sync");
    event=await db.labEvent.findUniqueOrThrow({where:{id:event.id}});
    await saveCalendarBooking(db,a,{...input,teamsEnabled:"on",startTime:"15:00",endTime:"16:00"},{id:event.id,version:event.version},now);
    await syncConnectedOutlookCalendars();
    assert.equal(calls.filter(c=>c.method==="PATCH"&&c.url.includes("/onlineMeetings/")).length,1);
    assert.equal(calls.filter(c=>c.method==="PATCH"&&c.url.includes("/events/")).length,2);
    await db.labEvent.delete({where:{id:event.id}});
    assert.equal(await db.outlookMeeting.count({where:{userId:a.id,eventId:null}}),1,"tombstone survives event deletion");
    await syncConnectedOutlookCalendars();
    assert.equal(calls.filter(c=>c.method==="DELETE"&&c.url.includes("/onlineMeetings/")).length,1);
    assert.equal(calls.filter(c=>c.method==="DELETE"&&c.url.includes("/events/")).length,2);
    assert.equal(await db.outlookMeeting.count({where:{userId:a.id}}),0);
    const workingFetch=globalThis.fetch;
    globalThis.fetch=async (input,init)=>String(input).endsWith("/createOrGet") ? new Response(null,{status:403}) : workingFetch(input,init);
    await saveCalendarBooking(db,a,{...input,title:`Denied Teams ${suffix}`,teamsEnabled:"on"},undefined,now);
    const beforeFailureCopies=calls.filter(c=>c.method==="POST"&&c.url.endsWith("/events")).length;
    await syncConnectedOutlookCalendars();
    assert.match((await db.outlookConnection.findUniqueOrThrow({where:{userId:a.id}})).lastError??"",/Teams meeting sync failed/);
    assert.equal(calls.filter(c=>c.method==="POST"&&c.url.endsWith("/events")).length,beforeFailureCopies+2,"Teams denial does not stop calendar sync");
    await db.labEvent.deleteMany({where:{ownerId:a.id}});
    await syncConnectedOutlookCalendars();
    globalThis.fetch=workingFetch;
    await db.outlookConnection.update({where:{userId:a.id},data:{refreshToken:""}});
    await assert.rejects(linkedMicrosoftUser(db,`ms-${a.id}`));
    count=calls.length;await syncConnectedOutlookCalendars();assert.equal(calls.length,count);
    console.log("PASS: meeting validation/ownership, linked-only sign-in, expired/wrong/tampered OAuth state, Teams scope gating, one organizer link shared with invitees, idempotency, reschedule and cancellation cleanup, disconnected sign-in rejection.");
  } finally {
    globalThis.fetch=originalFetch;
    await db.user.deleteMany({where:{id:{in:[a.id,b.id]}}});
    await db.$disconnect();
  }
}
main().catch(error=>{console.error(error);process.exitCode=1;});
